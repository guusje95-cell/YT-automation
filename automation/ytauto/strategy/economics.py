"""Scenario model for channel economics.

All inputs are ASSUMPTIONS (see strategy/financial_model.md for rationale).
Run:  python -m ytauto.strategy.economics  -> writes strategy/financial_model_output.md
"""
from __future__ import annotations

import math
from dataclasses import dataclass

from ytauto.core.log import ROOT


@dataclass
class Scenario:
    name: str
    views_m12: float          # monthly long-form views reached around month 12
    views_m24: float          # monthly long-form views around month 24
    ramp_mid: float           # month at which growth curve is at 50% of m12 level
    rpm_usd: float            # creator RPM (after YouTube's share, incl. unmonetized views)
    avd_min: float = 5.0      # average view duration in minutes
    subs_per_view: float = 0.008
    videos_per_month: int = 6
    cost_fixed_eur: float = 12.0      # software/hosting per month
    cost_per_video_eur: float = 0.6   # LLM tokens etc.
    sponsor_rpm_usd: float = 0.0      # extra revenue per 1k views from sponsors/affiliates once >=50k views/mo


SCENARIOS = [
    Scenario("stall (channel fails to gain traction)", views_m12=3_000, views_m24=4_000, ramp_mid=6, rpm_usd=2.5),
    Scenario("conservative", views_m12=25_000, views_m24=60_000, ramp_mid=9, rpm_usd=2.5),
    Scenario("base", views_m12=150_000, views_m24=400_000, ramp_mid=7, rpm_usd=4.5, sponsor_rpm_usd=1.5),
    Scenario("optimistic", views_m12=900_000, views_m24=2_000_000, ramp_mid=5, rpm_usd=8.0, sponsor_rpm_usd=4.0),
]

USD_EUR = 0.92
YPP_HOURS = 8_000     # reported threshold for new applicants from 2027-02-01 (secondary sources)
YPP_SUBS = 1_000
REVIEW_LAG_MONTHS = 1


def monthly_views(s: Scenario, month: int) -> float:
    """Logistic ramp to the m12 level, then linear growth toward m24."""
    if month <= 12:
        return s.views_m12 / (1 + math.exp(-(month - s.ramp_mid) / 1.5)) / \
            (1 / (1 + math.exp(-(12 - s.ramp_mid) / 1.5)))
    return s.views_m12 + (s.views_m24 - s.views_m12) * (month - 12) / 12


def simulate(s: Scenario, months: int = 24) -> list[dict]:
    rows, subs, hours_hist, eligible_from = [], 0.0, [], None
    cum_profit = 0.0
    for m in range(1, months + 1):
        v = monthly_views(s, m)
        subs += v * s.subs_per_view
        hours_hist.append(v * s.avd_min / 60)
        trailing = sum(hours_hist[-12:])
        if eligible_from is None and trailing >= YPP_HOURS and subs >= YPP_SUBS:
            eligible_from = m + REVIEW_LAG_MONTHS
        monetized = eligible_from is not None and m >= eligible_from
        ad = v / 1000 * s.rpm_usd * USD_EUR if monetized else 0.0
        spons = v / 1000 * s.sponsor_rpm_usd * USD_EUR if v >= 50_000 else 0.0
        cost = s.cost_fixed_eur + s.cost_per_video_eur * s.videos_per_month
        profit = ad + spons - cost
        cum_profit += profit
        rows.append(dict(month=m, views=round(v), subs=round(subs), trailing_hours=round(trailing),
                         monetized=monetized, ad_rev_eur=round(ad), other_rev_eur=round(spons),
                         cost_eur=round(cost), profit_eur=round(profit), cum_profit_eur=round(cum_profit)))
    return rows


def sensitivity_table() -> str:
    lines = ["| Monthly views | RPM $2.5 | RPM $4.5 | RPM $8 |", "|---|---|---|---|"]
    for v in (10_000, 50_000, 100_000, 250_000, 500_000, 1_000_000):
        cells = [f"€{v / 1000 * r * USD_EUR:,.0f}" for r in (2.5, 4.5, 8.0)]
        lines.append(f"| {v:,} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    out = ["# Financial model output (generated)", "",
           "Generated by `automation/ytauto/strategy/economics.py`. Every number is a modelled",
           "scenario from stated assumptions, **not a forecast or guarantee**.", "",
           "## Ad revenue per month by views and RPM (after YouTube's share, EUR)", "",
           sensitivity_table(), ""]
    for s in SCENARIOS:
        rows = simulate(s)
        elig = next((r["month"] for r in rows if r["monetized"]), None)
        be = next((r["month"] for r in rows if r["cum_profit_eur"] > 0 and r["monetized"]), None)
        out += [f"## Scenario: {s.name}", "",
                f"Assumptions: m12 views/mo {s.views_m12:,.0f}, m24 {s.views_m24:,.0f}, RPM ${s.rpm_usd}, "
                f"AVD {s.avd_min} min, {s.subs_per_view * 100:.1f} subs per 100 views, "
                f"{s.videos_per_month} videos/mo, fixed cost €{s.cost_fixed_eur}/mo, €{s.cost_per_video_eur}/video.", "",
                f"- Monetization (YPP, 8,000h rule) from month: **{elig or 'not within 24 months'}**",
                f"- Cumulative break-even month: **{be or 'not within 24 months'}**",
                f"- Month-24 profit: **€{rows[-1]['profit_eur']:,}/mo**; cumulative 24-month: **€{rows[-1]['cum_profit_eur']:,}**", "",
                "| Month | Views | Subs | Trailing 12m hours | Monetized | Ad € | Other € | Cost € | Profit € |",
                "|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            if r["month"] in (1, 3, 6, 9, 12, 15, 18, 21, 24):
                out.append(f"| {r['month']} | {r['views']:,} | {r['subs']:,} | {r['trailing_hours']:,} | "
                           f"{'yes' if r['monetized'] else 'no'} | {r['ad_rev_eur']:,} | {r['other_rev_eur']:,} | "
                           f"{r['cost_eur']} | {r['profit_eur']:,} |")
        out.append("")
    path = ROOT / "strategy" / "financial_model_output.md"
    path.write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
