"""Financial model for the top 3 (Autonomous Online Income Lab).

Every input is labelled: [F] = fact from a source, [E] = estimate anchored to sources, [A] = assumption.
Profit = pre-tax profit (before Dutch income tax/VAT settlement; platforms are merchant of record and remit VAT).
Run: python income_lab/models/financial_model.py  -> writes financial_output.md
"""
from math import ceil
from pathlib import Path

USD_EUR = 0.87  # [A] exchange rate; adjust to the current rate
TARGETS_EUR = [500, 2_500, 5_000, 10_000, 25_000, 50_000]

# ---------------------------------------------------------------- Atlassian Forge
ATL = {
    # hit = share of launched apps that reach "mature" (the rest earn ~nothing) [A]
    # ARPC = average monthly revenue per paying Jira/Confluence site (USD)
    # [A] anchor: per-user tier pricing on 25-150-user sites; Agile Docs ~$4.1k MRR [S]
    "conservatief": dict(arpc=40, conv=0.15, cust_per_app=40, churn=0.03, hit=0.20),
    "realistisch": dict(arpc=80, conv=0.25, cust_per_app=120, churn=0.025, hit=0.35),
    "optimistisch": dict(arpc=150, conv=0.35, cust_per_app=300, churn=0.02, hit=0.50),
}
ATL_FIXED_EUR = 175      # [E] AI tools €100, helpdesk/domain/mail €25, bookkeeping €50; Forge hosting within free quota [A]
ATL_FEE_BELOW_1M = 0.00  # [F] 0% until $1M lifetime Forge revenue (from 2026-01-01)
ATL_FEE_ABOVE_1M = 0.17  # [F] standard Forge rate from 2026-10-01 (83% partner share)

# ---------------------------------------------------------------- Apify
APIFY = {
    # net = monthly payout per published actor after 20% commission and platform costs (USD)
    # [E] anchors: 13 actors ~$8.5/actor/month in month 1 [S]; one strong actor ~$200/month [S];
    #     average per developer ≈ $1.7M/5,600 = $304/month [F-derived]
    "conservatief": dict(net=8, maint_h=0.5),
    "realistisch": dict(net=30, maint_h=0.3),
    "optimistisch": dict(net=90, maint_h=0.2),
}
APIFY_FIXED_EUR = 120    # [E] AI tools + small extra test proxies

# ---------------------------------------------------------------- JetBrains
JB = {
    # arpu = average monthly revenue per paying licence (USD); [A] personal ~$3-5, org ~$10-20/month
    "conservatief": dict(arpu=5, users_per_plugin=100),
    "realistisch": dict(arpu=8, users_per_plugin=300),
    "optimistisch": dict(arpu=12, users_per_plugin=800),
}
JB_FEE = 0.15            # [F]
JB_FIXED_EUR = 120       # [E]


def atl_rows():
    out = []
    for sc, p in ATL.items():
        for t in TARGETS_EUR:
            # Above ~ $83k/month revenue the $1M lifetime cap is reached within a year -> use 17% fee.
            gross_needed_usd = (t + ATL_FIXED_EUR) / USD_EUR
            fee = ATL_FEE_BELOW_1M if gross_needed_usd * 12 < 1_000_000 else ATL_FEE_ABOVE_1M
            rev_usd = gross_needed_usd / (1 - fee)
            cust = ceil(rev_usd / p["arpc"])
            apps = ceil(cust / p["cust_per_app"])
            built = ceil(apps / p["hit"])                          # apps to launch incl. flops
            new_cust_per_month = ceil(cust * p["churn"])          # replacement for churn
            trials_per_month = ceil(new_cust_per_month / p["conv"])
            hours = 3 + 1.0 * cust / 100 + 0.5 * built            # [E] base + support + maintenance per app
            out.append((sc, t, round(rev_usd), cust, apps, built, trials_per_month, round(hours, 1), f"{int(fee*100)}%"))
    return out


def apify_rows():
    out = []
    for sc, p in APIFY.items():
        for t in TARGETS_EUR:
            rev_usd = (t + APIFY_FIXED_EUR) / USD_EUR
            actors = ceil(rev_usd / p["net"])
            hours = 2 + actors * p["maint_h"] / 4.33              # [E] per week
            out.append((sc, t, round(rev_usd), actors, round(hours, 1)))
    return out


def jb_rows():
    out = []
    for sc, p in JB.items():
        for t in TARGETS_EUR:
            rev_usd = (t + JB_FIXED_EUR) / USD_EUR / (1 - JB_FEE)
            users = ceil(rev_usd / p["arpu"])
            plugins = ceil(users / p["users_per_plugin"])
            hours = 2 + plugins * 0.75 + users / 1000             # [E]
            out.append((sc, t, round(rev_usd), users, plugins, round(hours, 1)))
    return out


def md_table(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
    for r in rows:
        s += "| " + " | ".join(f"{x:,}" if isinstance(x, int) else str(x) for x in r) + " |\n"
    return s


def main():
    md = ["# Financial model: output (generated by financial_model.py)\n",
          f"Exchange rate [A]: 1 USD = {USD_EUR} EUR. 'Profit' = pre-tax profit per month in EUR. "
          "'Revenue' = gross marketplace revenue in USD. Hours = estimated owner hours per week. "
          "Atlassian fee: 0% until $1M lifetime revenue; at €50k/month you cross that after ~17 months, after which "
          "17% applies (~20% more revenue needed for the same profit).\n"]

    md.append("\n## 1. Atlassian Forge micro-apps\n")
    md.append("Inputs per scenario: " + "; ".join(
        f"**{k}**: ARPC ${v['arpc']}/month, trial→paid {int(v['conv']*100)}%, "
        f"{v['cust_per_app']} payers per mature app, hit rate {int(v['hit']*100)}%, churn {v['churn']*100:.1f}%/month" for k, v in ATL.items()) + "\n\n")
    md.append(md_table(["Scenario", "Profit target €/month", "Revenue $/month", "Paying customers",
                        "Successful apps", "Apps to launch (incl. flops)", "Trials/month to cover churn", "Hours/week", "Fee yr 1"],
                       atl_rows()))

    md.append("\n## 2. Apify Store actor portfolio\n")
    md.append("Inputs: net payout per actor per month: " + ", ".join(
        f"**{k}** ${v['net']}" for k, v in APIFY.items()) + " (after 20% commission and compute costs).\n\n")
    md.append(md_table(["Scenario", "Profit target €/month", "Net payout $/month", "Active actors needed",
                        "Hours/week"], apify_rows()))

    md.append("\n## 3. JetBrains paid plugins\n")
    md.append(md_table(["Scenario", "Profit target €/month", "Gross revenue $/month", "Paying licences",
                        "Plugins needed", "Hours/week"], jb_rows()))

    out = "".join(md)
    Path(__file__).with_name("financial_output.md").write_text(out)
    print(out)


if __name__ == "__main__":
    main()
